# ============================================================
# GENERATION FUNCTION
# ============================================================

async def generate_segment(segment):
    """Generate audio for one segment"""
    output_file = OUTPUT_DIR / f"VO_{segment['id']}.mp3"

    # Clean text for TTS (remove markup)
    text = segment['text']

    communicate = edge_tts.Communicate(
        text=text,
        voice=VOICE,
        rate=RATE,
        volume=VOLUME
    )

    print(f"Generating {segment['id']}...")
    await communicate.save(str(output_file))
    print(f"  ✓ Saved: {output_file}")
    return output_file

async def main():
    print(f"Using voice: {VOICE}")
    print(f"Output dir: {OUTPUT_DIR}")
    print(f"Segments: {len(SCRIPT_SEGMENTS)}")
    print("-" * 50)

    for segment in SCRIPT_SEGMENTS:
        try:
            await generate_segment(segment)
        except Exception as e:
            print(f"  ✗ Error on {segment['id']}: {e}")

    print("-" * 50)
    print("Done! Check output folder.")

if __name__ == "__main__":
    asyncio.run(main())